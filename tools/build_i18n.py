#!/usr/bin/env python3
"""Build deterministic UTF-8 MonZaMac UI catalogs from reviewed translations.

English source text is the stable lookup key. Omitted translations are not
invented; the runtime falls back to the original English entry.
"""
from __future__ import annotations
import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
I18N = ROOT / 'i18n'
LANGUAGES = ('en', 'it', 'fr', 'es', 'de', 'pt-BR', 'ja', 'zh-Hans', 'zh-Hant', 'ko', 'ru')


def unescape(s: str) -> str:
    """Decode the documented TSV escapes, preserving significant spaces."""
    out = []
    i = 0
    escapes = {'n': '\n', 'r': '\r', 't': '\t', 's': ' ', '\\': '\\'}
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s) and s[i + 1] in escapes:
            out.append(escapes[s[i + 1]])
            i += 2
        else:
            out.append(s[i])
            i += 1
    return ''.join(out)


def source_data():
    """Single source of truth for every localized UI label and description."""
    table: dict[str, dict[str, str]] = {}
    with (I18N / 'translations.tsv').open(encoding='utf-8', newline='') as src:
        reader = csv.DictReader(src, delimiter='\t')
        if tuple(reader.fieldnames or ()) != LANGUAGES:
            raise ValueError('Unexpected localization columns')
        for n, row in enumerate(reader, 2):
            en = unescape(row['en'])
            if not en or en in table:
                raise ValueError(f'Invalid/duplicate English source at row {n}: {en!r}')
            values = {lang: unescape(row[lang]) for lang in LANGUAGES[1:]
                      if row.get(lang) and unescape(row[lang])}
            table[en] = values
    return table


FORMAT = re.compile(r"(?<![0-9])%(?:\d+\$)?[-+#0]*\d*(?:\.\d+)?(?:hh|ll|[hlzLjt])?[%diuoxXfFeEgGaAcsp]")


def placeholders(s):
    return [m.group(0) for m in FORMAT.finditer(s) if m.group(0) != '%%']


def escape(s):
    out = s.replace('\\', '\\\\').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    pad = len(out) - len(out.rstrip(' '))
    return out[:-pad] + '\\s' * pad if pad else out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--verify', action='store_true', help='check that generated catalogs are current')
    args = ap.parse_args()
    table = source_data()
    files = {}
    for lang in LANGUAGES:
        content = ['# Generated by tools/build_i18n.py; edit i18n/translations.tsv instead.']
        for key, values in sorted(table.items()):
            val = key if lang == 'en' else values.get(lang)
            if not val:
                continue
            if lang != 'en' and placeholders(key) != placeholders(val):
                raise ValueError(f'{lang}: placeholders do not match in {key!r}: {placeholders(key)} vs {placeholders(val)}')
            content.append(f'{escape(key)}\t{escape(val)}')
        files[lang] = '\n'.join(content) + '\n'
    for lang, content in files.items():
        target = I18N / 'catalog' / f'{lang}.tsv'
        if args.verify:
            if not target.is_file() or target.read_text(encoding='utf-8') != content:
                raise ValueError(f'Stale catalog: {target}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding='utf-8')
    print(f'{len(table)} English keys; translated keys per language: ' +
          ', '.join(f'{lang}={sum(bool(v.get(lang)) for v in table.values())}' for lang in LANGUAGES[1:]))


if __name__ == '__main__':
    main()
